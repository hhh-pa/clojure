//! Link settings for the `clojure-rs` binary on Linux (#226). Both cut
//! the binary pages every run touches, which count in its peak RSS.

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=hot-text.ld");
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("linux") {
        return;
    }
    // A fixed-address (non-PIE) executable. A PIE's loader applies
    // ~18,000 relative relocations at every start: it reads all
    // 420 KB of `.rela.dyn` and writes the 300 KB `.data.rel.ro`
    // table. Non-PIE resolves them at link time, and a run only
    // touches the table pages it reads.
    println!("cargo:rustc-link-arg-bins=-no-pie");
    // Release links pack the functions a typical run executes into
    // one `.text.hot` section (`hot-text.ld`, generated by
    // `scripts/bench/hot-text/run.sh`): left scattered, the ~1 MB a
    // trivial run executes spans 5 MB of `.text` pages.
    let dir = std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR");
    let script = std::path::Path::new(&dir).join("hot-text.ld");
    if std::env::var("PROFILE").as_deref() == Ok("release") && script.exists() {
        println!("cargo:rustc-link-arg-bins=-Wl,-T,{}", script.display());
    }
}
