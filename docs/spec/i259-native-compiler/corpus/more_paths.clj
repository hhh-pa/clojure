;; Rarer runtime paths: finally on an uncaught throw, set! without a binding,
;; unhashable case keys, nested map patterns, :pre/:post, static-field constants.
(def ^:dynamic *d* 1)
(defn f1 [] (try (try (throw (ex-info "in" {})) (catch ArithmeticException _ :no) (finally (println "fin-runs"))) (catch Exception e (ex-message e))))
(println (f1))
(defn f2 [] (try (set! *d* 2) (catch Exception e (.getMessage e))))
(println (f2))
(defn f3 [x] (try (case x 1 :a [1] :v :b) (catch Exception e (class e))))
(println (f3 (repeat 1)) (f3 (range)))
(defn f4 [m] (let [{[a b] :pair x :x} m] [a b x]))
(println (f4 {:pair [1 2] :x 3}))
(defn f5 [{{[p & ps] :ps} :inner :as all}] [p ps (count all)])
(println (f5 {:inner {:ps [1 2 3]}}))
(defn pre [x] {:pre [(pos? x)] :post [(< % 100)]} (* x 2))
(println (pre 3) (try (pre -1) (catch AssertionError e (.getMessage e))) (try (pre 60) (catch AssertionError e (.getMessage e))))
(println (str java.util.Locale/US))
(defn f6 [x] (try (let [{:keys [a]} x] a) (catch Exception e (class e))))
(println (f6 '(1 2 3)))
(println (f3 (map identity [(range)])))
