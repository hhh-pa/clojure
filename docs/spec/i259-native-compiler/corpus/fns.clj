;; Fns: arities, variadics, closures, recursion, var redefinition, macros.
(ns user.fns (:require [clojure.string :as str]))
(defn multi ([] :zero) ([a] [:one a]) ([a b] [:two a b]) ([a b & more] [:many a b more]))
(println (multi) (multi 1) (multi 1 2) (multi 1 2 3 4))
(defn fixed2 [a b] (+ a b))
(println (try (apply fixed2 [1]) (catch clojure.lang.ArityException e (.getMessage e))))
(defn make-adder [n] (fn [x] (+ x n)))
(def add5 (make-adder 5))
(println (add5 10) (map (make-adder 1) [1 2 3]))
(defn counter []
  (let [c (atom 0)]
    {:inc (fn [] (swap! c inc)) :get (fn [] @c)}))
(let [{:keys [inc get]} (counter)] (inc) (inc) (println (get)))
(defn fact [n] (if (<= n 1) 1 (* n (fact (dec n)))))
(println (fact 20))
(defn fib [n] (if (< n 2) n (+ (fib (- n 1)) (fib (- n 2)))))
(println (fib 20))
(defn deep [n] (if (zero? n) 0 (inc (deep (dec n)))))
(println (deep 5000))
(println (try (deep 10000000) (catch StackOverflowError _ :so)))
(defn twice [x] (* 2 x))
(defn use-twice [x] (twice x))
(println (use-twice 4))
(defn twice [x] (* 3 x))
(println (use-twice 4))
(def twice :not-a-fn)
(println (try (use-twice 4) (catch Exception _ :not-fn)))
(defmacro unless [c & body] `(if ~c nil (do ~@body)))
(println (unless false :ran) (unless true :never))
(defmacro twice-m "doc" [x] `(do ~x ~x))
(twice-m (print "x"))
