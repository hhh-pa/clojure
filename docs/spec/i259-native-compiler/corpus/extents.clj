;; Extent forms: with-redefs, binding, time, with-out-str, with-in-str,
;; locking, dosync/io!, try/catch/finally, throw.
(defn greet [] "hi")
(defn uses-greet [] (greet))
(println (with-redefs [greet (fn [] "redef")] (uses-greet)) (uses-greet))
(def ^:dynamic *x* 1)
(println (with-bindings {#'*x* 2} *x*))
(println (pos? (count (with-out-str (time (reduce + (range 100)))))))
(println (with-out-str (print "captured") (print 1)))
(println (with-in-str "line one\nline two" [(read-line) (read-line)]))
(def lock (Object.))
(println (locking lock (+ 1 2)))
(def r (ref 0))
(dosync (alter r inc) (alter r + 10))
(println @r)
(println (io! :io-ok))
(defn safe-div [a b]
  (try (/ a b)
       (catch ArithmeticException e (str "caught " (.getMessage e)))
       (finally (println "finally" a b))))
(println (safe-div 6 3) (safe-div 1 0))
(println (try (throw (ex-info "boom" {:k 1})) (catch clojure.lang.ExceptionInfo e (ex-data e))))
(println (try (throw (RuntimeException. "rt")) (catch IllegalStateException _ :ise) (catch Exception e [:ex (.getMessage e)])))
(println (try (nth [1] 5) (catch IndexOutOfBoundsException _ :ioobe)))
(println (try :body (finally (println "only finally"))))
(defn rethrow [] (try (throw (Exception. "inner")) (catch Exception e (throw (RuntimeException. (str "outer:" (.getMessage e)))))))
(println (try (rethrow) (catch Exception e (.getMessage e))))
(println (lazy-seq (cons 1 (lazy-seq [2 3]))))
(defn nums [n] (lazy-seq (when (pos? n) (cons n (nums (dec n))))))
