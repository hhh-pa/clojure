(defn bump [xs i] (assoc xs i (inc (nth xs i))))
(defn lower-one [xs i] (assoc xs i (dec (nth xs i))))
(defn replace-one [xs i value] (assoc xs i value))
(defn bump-and-keep [xs i] [(assoc xs i (inc (nth xs i))) xs])
(defn bump-from-first [xs i] (assoc xs i (inc (nth xs 0))))

(let [xs [4 9]]
  (println (bump xs 1) (lower-one xs 0) (bump-and-keep xs 0) xs))
(println (bump [7 :mixed] 0) (bump [1.5 2.5] 0))
(println (bump-from-first [1 8] 1))
(println (replace-one [1] 1 2) (replace-one {:a 2} :a 3)
         (replace-one (sorted-map :a 2) :a 3))
(println (try (bump [9223372036854775807] 0)
              (catch ArithmeticException _ :overflow)))
(println (try (bump [0] 1)
              (catch IndexOutOfBoundsException _ :outside)))
(println (try (bump [0] 4294967296)
              (catch Exception e (class e))))
(println (try (bump '(0) 0)
              (catch Exception e (class e))))
