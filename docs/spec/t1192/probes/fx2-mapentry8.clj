(def e (first {:a 1}))
(defn show [label v] (println label (pr-str v)))
(defn throwof [label form]
  (println label (try (eval form)
                      (catch Throwable t (str "THROW " (.getName (class t)) "|" (pr-str (.getMessage t)))))))
(throwof "rseq-list:" '(rseq (quote (1 2 3))))
(throwof "rseq-map:" '(rseq {:a 1}))
(throwof "rseq-nil:" '(rseq nil))
(show "rseq-empty:" (rseq []))
(show "rseq-empty-class:" (try (class (rseq [])) (catch Throwable t (str "THROW:" (.getName (class t))))))
(show "rseq-counted:" (counted? (rseq [:a 1])))
(show "rseq-count:" (count (rseq [:a 1])))
(show "rseq-first:" (first (rseq [:a 1])))
(show "case-entry:" (case e [:a 1] :hit :miss))
(throwof "compare-vec-list:" '(compare [1] (quote (2))))
(throwof "compare-entry-list:" '(compare e (quote (:a 2))))
(show "compare-entry-str:" (try (compare e "x") (catch ClassCastException t (str "CCE|" (.getMessage t)))))
