;; NOTE: pe prints the full cause chain with file paths normalized to (<file>).
;; defn/def/let/loop/fn/recur shapes are NOT S5D scope (see MANIFEST).
(defn p [tag thunk]
  (print tag " => ")
  (prn (try (thunk)
            (catch Throwable t
              (str "THROW " (.getName (class t)) ": " (.getMessage t))))))
(defn norm [s]
  (if (string? s) (clojure.string/replace s #"\(/[^\s:)]*" "(<file>") s))
(defn pe [tag thunk]
  (print tag " => ")
  (prn (try (thunk)
            (catch Throwable t
              (loop [t t acc []]
                (if (nil? t) acc
                    (recur (.getCause t) (conj acc (str (.getName (class t)) " | " (norm (str (.getMessage t))))))))))))

