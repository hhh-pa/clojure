(defmacro t [label expr]
  `(.write *out* (str ~label " => "
                      (clojure.string/escape
                       (str (try ~expr
                                 (catch Throwable e# (str (.getName (class e#)) ": " (.getMessage e#)))))
                       {\newline "\\n"})
                      "\n")))
(t "p1 scalars" (with-out-str (println "a" 1 :k \c 2.5 nil true)))
(t "p2 print str" (with-out-str (print "b\n")))
(t "p3 pr scalars" (with-out-str (prn "s" 1 :k)))
(t "p4 join" (with-out-str (println (clojure.string/join " " [1 2 3]))))
(t "q1 numbers" (with-out-str (prn 1.0 1.5 1.0E7 12345678.0 0.001 1.0E-4 3.0 (float 1) ##NaN ##Inf (- ##Inf) -0.0 (double 7) 1e21 7.0)))
(t "q2 big numbers" (with-out-str (prn 12345678901234567890 1.5M 1/3 (- 1) (bigint 7) 2N 3.0M 22/7 (double 22/7))))
(t "q3 chars strings" (with-out-str (prn \a \newline \tab \formfeed \backspace \return \u00e9 "s\nq\"z\\é" (str \a) (name :a/b) (namespace 'a/b))))
(t "q4 not readable" (with-out-str (binding [*print-readably* nil] (pr "a" :k 'sym \b 1.0 (keyword "a b")) (print "c" \d))))
(t "q5 meta" (with-out-str (binding [*print-meta* true] (pr (with-meta 'sym {:a 1}) (with-meta :k {:b 2}) (with-meta "s" {:c 3})))))
(t "q6 dup pristine" (with-out-str (binding [*print-dup* true] (prn 1 "h" :k 1.0 [1 "s"]))))
(t "q7 writer" (let [w (java.io.StringWriter.)] (binding [*out* w] (println "x" 1) (pr "y") (newline) (.flush w)) (str w)))
(t "q8 pieces" (with-out-str (print "a") (print 1) (newline) (pr) (print) (prn) (println)))
(t "q9 limits" (with-out-str (binding [*print-length* 1 *print-level* 1] (prn 1 "s" :k))))
(t "q10 pr-str" [(pr-str "tab\there" \c) (prn-str 1 "a") (print-str 1 "a") (println-str 1 "a")])
(t "q11 names" (with-out-str (prn ::k 'user/s (symbol "x") '/ '/ 'a-b 'a/b (symbol "a b") 'foo.bar/baz-qux :foo.bar/baz-qux)))
(t "q12 unicode" (with-out-str (prn "é中ß€") (println "é中ß€")))
(t "q13 mixed" (with-out-str (println [1 "a"] {:a 1} #{1} '(1 2) nil) (prn [1 "a" \b])))
(t "q14 nils" (with-out-str (println nil nil) (pr nil nil) (print nil)))
(t "q15 ns maps" (with-out-str (binding [*print-namespace-maps* true] (prn {:a/b 1}))))
(t "q16 int kinds" (with-out-str (prn -5 0 (int 5) (short 5) (byte 5) 5 (Integer/MAX_VALUE) (Long/MAX_VALUE) 2147483648)))
(t "p5 defmethod" (do (defmethod print-method String [s w] (.write w (str "<" s ">"))) :ok))
(t "p6 after defmethod" (with-out-str (println "c" 2) (print "d\n") (prn "e")))
(t "p7 nested" (with-out-str (println (with-out-str (print "f")))))
(t "p8 long method" (do (defmethod print-method Long [n w] (.write w (str "#" n))) (with-out-str (println "g" 3))))
(t "p9 print-dup" (with-out-str (binding [*print-dup* true] (prn 1 "h"))))
(t "p10 pr-str" [(pr-str "j") (str "k")])
