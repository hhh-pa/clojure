(defmacro t [label expr]
  `(println ~label "=>"
            (try (pr-str ~expr)
                 (catch Throwable e# (str (.getName (class e#)) ": " (.getMessage e#))))))
(def E clojure.lang.PersistentQueue/EMPTY)
(def q (conj E 1 2 3))
(t "q1 pr" q)
(t "q2 str" (str q))
(t "q3 print" (with-out-str (print q)))
(t "q4 seq" (seq q))
(t "q5 empty-seq" (seq E))
(t "q6 count" (count q))
(t "q7 peek" (peek q))
(t "q8 pop" (pop q))
(t "q9 pop-empty" (pop E))
(t "q10 peek-empty" (peek E))
(t "q11 empty?" [(empty? E) (empty? q)])
(t "q12 = vec" [(= q [1 2 3]) (= [1 2 3] q) (= q '(1 2 3))])
(t "q13 = queue" (= q (conj E 1 2 3)))
(t "q14 class" (class q))
(t "q15 vector?" [(vector? q) (seq? q) (sequential? q) (coll? q) (counted? q)])
