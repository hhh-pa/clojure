;; ---- H: LNPR wraps (positions + entry-check order) ----
(defn exdataof [label form]
  (try
    (let [v (eval form)]
      (println (str label " " (pr-str v))))
    (catch clojure.lang.LispReader$ReaderException t
      (println (str label " READEREX " (pr-str (.getMessage t)) " exdata=" (pr-str (ex-data t)) " cause=" (.getName (class (.getCause t))))))
    (catch Throwable t
      (println (str label " THROW " (.getName (class t)) "|" (pr-str (.getMessage t)))))))
