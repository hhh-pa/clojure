(tx "post-shape" (fn [] (macroexpand-1 '(fn [x] {:post [(pos? %)]} x))))
(tx "post-pass" (fn [] ((fn [x] {:post [(pos? %)]} x) 5)))
(tx "nil-runtime-invoke" #(eval '(let [f nil] (f 1))))
(tx "unbound-plus" (fn [] (do (eval '(def ub2026)) (eval '(+ ub2026 1)))))
