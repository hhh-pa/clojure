;; S4 oracle probes: analyzer + invocation error texts.
;; Exit 0 (all errors caught and printed as class | message).
;; Malformed shapes go through eval (raw ones would kill this file).
(defn tx [label f]
  (println label "=>" (pr-str (try (f) (catch Throwable t
    (loop [t t acc []] (if t (recur (.getCause t) (conj acc (str (.getName (class t)) " | " (.getMessage t)))) acc)))))))
(tx "(eval '(if 1))" #(eval '(if 1)))
(tx "(eval '(if 1 2 3 4))" #(eval '(if 1 2 3 4)))
(tx "(eval '(quote))" #(eval '(quote)))
(tx "(eval '(quote a b))" #(eval '(quote a b)))
(tx "(eval '(let [x] x))" #(eval '(let [x] x)))
(tx "(eval '(let x x))" #(eval '(let x x)))
(tx "(eval '(let [1 2] 1))" #(eval '(let [1 2] 1)))
(tx "(eval '(loop [x] x))" #(eval '(loop [x] x)))
(tx "(eval '(fn [1] 1))" #(eval '(fn [1] 1)))
(tx "(eval '(var))" #(eval '(var)))
(tx "(eval '(throw))" #(eval '(throw)))
(tx "(eval '(set! x))" #(eval '(set! x)))
(tx "(eval '(try 1 (catch)))" #(eval '(try 1 (catch))))
(tx "(eval '(catch Exception e 1))" #(eval '(catch Exception e 1)))
(tx "(eval '(recur 1))" #(eval '(recur 1)))
(tx "recur-non-tail" #(eval '((fn [x] (inc (recur x))) 1)))
(tx "recur-mismatch" #(eval '(loop [a 1 b 2] (recur 1))))
(tx "fn-arity-1" #(eval '((fn [x] x) 1 2)))
(tx "fn-arity-multi" #(eval '((fn ([x] x) ([x y] y)) 1 2 3)))
