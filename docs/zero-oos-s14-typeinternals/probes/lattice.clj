(defn chain [^Class c]
  (loop [c c, out []]
    (if (nil? c) out (recur (.getSuperclass c) (conj out (.getName c))))))
(defn dump [label ^Class c]
  (println (str label " chain=" (pr-str (chain c)) " supers=" (pr-str (sort (map str (supers c)))))))
(defn dumpn [label ^String n]
  (try
    (dump label (Class/forName n))
    (catch Throwable t
      (println (str label " THROW " (.getName (class t)))))))
(defn dumpv [label v]
  (dump label (class v)))
