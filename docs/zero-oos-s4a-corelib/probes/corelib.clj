(require 'clojure.string)
(defn throwof [label form]
  (try
    (let [v (eval form)]
      (println (str label " " (pr-str v))))
    (catch Throwable t
      (println (str label " THROW " (.getName (class t)) "|" (pr-str (.getMessage t)))))))
(defn throwcause [label form]
  (try
    (let [v (eval form)]
      (println (str label " " (pr-str v))))
    (catch Throwable t
      (let [c (loop [x t] (let [n (.getCause ^Throwable x)] (if n (recur n) x)))
            m (-> (or (.getMessage ^Throwable c) "<nil>")
                  (clojure.string/replace #"eval\d+" "evalN")
                  (clojure.string/replace #"--\d+" "--N")
                  (clojure.string/replace #"@[0-9a-fA-F]+" "@H"))]
        (println (str label " THROW " (.getName (class c)) "|" (pr-str m)))))))
;; normexp: stabilize gensyms in macroexpansion pins.
(defn normexp [s]
  (-> s
      (clojure.string/replace #"G__\d+" "G__N")
      (clojure.string/replace #"xs__\d+__auto__" "xs__N__auto__")))
